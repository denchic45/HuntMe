export function useFaq(initialOpenId: string | null = '1') {
  const roleStore = useLandingRoleStore()
  const activeFaqId = ref<string | null>(initialOpenId)

  const faqList = computed<FaqItem[]>(() => {
    return roleStore.isCandidate ? candidateFaq : employerFaq
  })

  function toggleFaq(id: string) {
    activeFaqId.value = activeFaqId.value === id ? null : id
  }

  function openFaq(id: string) {
    activeFaqId.value = id
  }

  function closeFaq() {
    activeFaqId.value = null
  }

  return {
    faqList,
    activeFaqId,
    toggleFaq,
    openFaq,
    closeFaq,
  }
}
